#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.txt: the Rust crates compiled into the wheel's native extensions.

    python scripts/third_party_notices.py           # regenerate
    python scripts/third_party_notices.py --check   # exit 1 if the committed file is stale (release check)

Lists every crate in the normal (non-dev, non-build-only) dependency closure of pgw-fast, pgw-ntt and
pgw-pks for the platforms we ship, with its version, SPDX license expression and repository, using
``cargo metadata`` (offline, from Cargo.lock). Python dependencies are installed separately by pip and
carry their own licenses.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # pgw/
OUT = ROOT / "THIRD_PARTY_NOTICES.txt"
ROOTS = ("pgw-fast", "pgw-ntt", "pgw-pks")
OURS = {"pgw-core-rs", "pgw-fast", "pgw-lane", "pgw-ntt", "pgw-pks"}


def _closure() -> list[dict[str, str]]:
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"],  # noqa: S607
        cwd=ROOT / "rust", check=True, capture_output=True, text=True).stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    todo = [pid for pid, p in pkgs.items() if p["name"] in ROOTS]
    seen: set[str] = set()
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            # Keep normal dependencies only (dev-dependencies are not linked into the extension;
            # build-dependencies run at build time only).
            if any(k.get("kind") is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    rows = []
    for pid in seen:
        p = pkgs[pid]
        if p["name"] in OURS:
            continue
        rows.append({"name": p["name"], "version": p["version"], "license": p.get("license") or "see crate",
                     "repository": p.get("repository") or ""})
    return sorted(rows, key=lambda r: (r["name"], r["version"]))


def render() -> str:
    rows = _closure()
    lines = [
        "Third-party software in the PGW native extensions (pgw_fast, pgw_ntt, pgw_pks)",
        "=" * 79,
        "",
        "The compiled extensions statically link the following open-source Rust crates. Each is used",
        "under the license shown (SPDX expression; where a choice is offered, any one applies). Full",
        "license texts are in each crate's source distribution at the repository listed.",
        "Generated by scripts/third_party_notices.py from rust/Cargo.lock; do not edit by hand.",
        "",
    ]
    w = max(len(f"{r['name']} {r['version']}") for r in rows)
    for r in rows:
        lines.append(f"{(r['name'] + ' ' + r['version']).ljust(w)}  {r['license']}  {r['repository']}".rstrip())
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.name} is stale: run python scripts/third_party_notices.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
