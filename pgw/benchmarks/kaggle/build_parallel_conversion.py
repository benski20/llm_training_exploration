#!/usr/bin/env python3
"""Build the Kaggle kernel for ``benchmarks/parallel_conversion.py`` (training-free parallel conversion, T4 x 2).

    python benchmarks/kaggle/build_parallel_conversion.py <out_root> [--slug pgw-parconv] [--owner bensliv] [-- args]

writes ``<out_root>/<slug>/{run.py,kernel-metadata.json}``; ``run.py`` carries the script and the shared harness
(``benchmarks/depth_prune_heal.py``) inline and writes its outputs to ``/kaggle/working/out``. No pgw source is
needed. Push with ``kaggle kernels push -p <dir>``.
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPTS = [HERE.parent / "depth_prune_heal.py", HERE.parent / "parallel_conversion.py"]

TEMPLATE = '''"""pgw training-free parallel conversion on Kaggle (generated by benchmarks/kaggle/build_parallel_conversion.py)."""
import base64
import os
import subprocess
import sys
import time

FILES = __FILES__
ARGS = __ARGS__
OUT = "/kaggle/working/out"
os.makedirs(OUT, exist_ok=True)
for name, src in FILES.items():
    with open("/kaggle/working/" + name, "wb") as f:
        f.write(base64.b64decode("".join(src)))
subprocess.run("nvidia-smi; nproc; free -g; df -h / /kaggle/working; "
               "python -c 'import torch, transformers, datasets; print(torch.__version__, transformers.__version__, "
               "datasets.__version__)'", shell=True)
t0 = time.time()
env = {**os.environ, "PYTHONUNBUFFERED": "1", "TOKENIZERS_PARALLELISM": "false",
       "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True", "HF_HUB_DISABLE_PROGRESS_BARS": "1"}
rc = subprocess.call([sys.executable, "-u", "/kaggle/working/parallel_conversion.py", *ARGS, "--out", OUT], env=env)
print("exit", rc, "minutes", round((time.time() - t0) / 60, 1), flush=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_root")
    ap.add_argument("--slug", default="pgw-parconv")
    ap.add_argument("--owner", default="bensliv")
    ap.add_argument("--machine", default="NvidiaTeslaT4", help="NvidiaTeslaT4 (one GPU, one queue) or NvidiaTeslaT4x2")
    ap.add_argument("rest", nargs="*")
    a = ap.parse_args()
    files = {}
    for p in SCRIPTS:
        b = base64.b64encode(p.read_bytes()).decode()
        files[p.name] = [b[i:i + 100] for i in range(0, len(b), 100)]
    d = Path(a.out_root) / a.slug
    d.mkdir(parents=True, exist_ok=True)
    body = json.dumps(files, indent=0)
    (d / "run.py").write_text(TEMPLATE.replace("__FILES__", body).replace("__ARGS__", json.dumps(a.rest)))
    meta = {"id": f"{a.owner}/{a.slug}", "title": a.slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "machine_shape": a.machine, "dataset_sources": [], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(d)


if __name__ == "__main__":
    main()
