#!/usr/bin/env python3
"""Build the Kaggle kernel for ``benchmarks/depth_prune_heal.py`` (shallower / parallel students, T4 x 2).

    python benchmarks/kaggle/build_depth.py <out_root> [--slug pgw-depth-05b] [--owner bensliv] [-- <script args>]

writes ``<out_root>/<slug>/{run.py,kernel-metadata.json}``; ``run.py`` carries the script inline and writes its
outputs to ``/kaggle/working/out``. No pgw source is needed. Push with ``kaggle kernels push -p <dir>``.
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE.parent / "depth_prune_heal.py"

TEMPLATE = '''"""pgw depth pruning / parallel-block healing on Kaggle (generated by benchmarks/kaggle/build_depth.py)."""
import base64
import os
import subprocess
import sys
import time

SRC = (__SRC__)
ARGS = __ARGS__
OUT = "/kaggle/working/out"
os.makedirs(OUT, exist_ok=True)
with open("/kaggle/working/depth_prune_heal.py", "wb") as f:
    f.write(base64.b64decode(SRC))
subprocess.run("nvidia-smi; nproc; free -g; df -h / /kaggle/working; "
               "python -c 'import torch, transformers, datasets; print(torch.__version__, transformers.__version__, "
               "datasets.__version__)'", shell=True)
t0 = time.time()
env = {**os.environ, "PYTHONUNBUFFERED": "1", "TOKENIZERS_PARALLELISM": "false",
       "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True", "HF_HUB_DISABLE_PROGRESS_BARS": "1"}
rc = subprocess.call([sys.executable, "-u", "/kaggle/working/depth_prune_heal.py", *ARGS, "--out", OUT], env=env)
print("exit", rc, "minutes", round((time.time() - t0) / 60, 1), flush=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_root")
    ap.add_argument("--slug", default="pgw-depth-05b")
    ap.add_argument("--owner", default="bensliv")
    ap.add_argument("rest", nargs="*")
    a = ap.parse_args()
    b = base64.b64encode(SCRIPT.read_bytes()).decode()
    src = "\n".join(f"    {b[i:i + 100]!r}" for i in range(0, len(b), 100))
    d = Path(a.out_root) / a.slug
    d.mkdir(parents=True, exist_ok=True)
    (d / "run.py").write_text(TEMPLATE.replace("__SRC__", "\n" + src + "\n").replace("__ARGS__", json.dumps(a.rest)))
    meta = {"id": f"{a.owner}/{a.slug}", "title": a.slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "machine_shape": "NvidiaTeslaT4x2", "dataset_sources": [], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(d)


if __name__ == "__main__":
    main()
