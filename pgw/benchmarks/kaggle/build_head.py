#!/usr/bin/env python3
"""Build the Kaggle draft-head distillation kernels (``benchmarks/feature_head_distill.py`` on a T4 x 2).

    python benchmarks/kaggle/build_head.py <out_root> [--only pgw-head-05b] [--owner bensliv]

writes ``<out_root>/<slug>/{run.py,kernel-metadata.json}``. ``run.py`` carries the three scripts it needs
(``feature_head_distill.py``, ``feature_head_train.py``, ``tree_spec_sim.py``) inline, writes them to
``/kaggle/working/src`` and runs the distillation with the job's arguments; outputs land in
``/kaggle/working/out`` (head files, ranks, eval answers, summary, log). No pgw source is needed: the head
only needs the target checkpoint and the public prompt datasets. Each kernel stays under 3 hours (the
script's own ``--budget-min`` ends it first).
"""

from __future__ import annotations

import argparse
import base64
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
FILES = ("feature_head_distill.py", "feature_head_train.py", "tree_spec_sim.py")

#: Target revisions: the SDK's pins (pgw.sdk.provisioning.PINNED_MODELS).
REV_05B = "7ae557604adf67be50417f59c2c2f167def9a775"
REV_7B = "a09a35458c702b33eeacc393d103063234e8bc28"

JOBS: dict[str, dict] = {
    # 0.5B: one GPU generates (~8M rows), then two configs train in parallel, one per GPU (~1.7 h in all)
    "pgw-head-05b": {"args": ["--target", "Qwen/Qwen2.5-0.5B-Instruct", "--revision", REV_05B,
                              "--n-train", "60000", "--max-rows", "8000000", "--gen-batch", "192",
                              "--kv-tokens", "200000", "--prefill-tokens", "32768",
                              "--configs", "256:16384,384:32768", "--epochs", "10", "--budget-min", "105",
                              "--gen-share", "0.42"]},
    # 7B: fp16 over both T4s (device_map auto, 8 GiB of weights each), ~4.5M rows, two configs in parallel
    "pgw-head-7b": {"args": ["--target", "Qwen/Qwen2.5-7B-Instruct", "--revision", REV_7B,
                             "--n-train", "30000", "--max-rows", "4500000", "--gen-batch", "96",
                             "--kv-tokens", "64000", "--prefill-tokens", "12288", "--max-memory", "8GiB",
                             "--configs", "384:16384,512:32768", "--epochs", "8", "--budget-min", "165",
                             "--gen-share", "0.58"]},
}

TEMPLATE = '''"""pgw draft-head distillation on Kaggle (generated by benchmarks/kaggle/build_head.py; do not edit the copy)."""
import base64
import os
import subprocess
import sys
import time

FILES = __FILES__
ARGS = __ARGS__
SRC, OUT = "/kaggle/working/src", "/kaggle/working/out"
os.makedirs(SRC, exist_ok=True)
os.makedirs(OUT, exist_ok=True)
for name, b64 in FILES.items():
    with open(os.path.join(SRC, name), "wb") as f:
        f.write(base64.b64decode(b64))
subprocess.run("nvidia-smi; nproc; free -g; df -h / /tmp /kaggle/working; "
               "python -c 'import torch, transformers; print(torch.__version__, transformers.__version__)'",
               shell=True)
t0 = time.time()
env = {**os.environ, "PYTHONUNBUFFERED": "1", "TOKENIZERS_PARALLELISM": "false",
       "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True"}
with open(os.path.join(OUT, "train.log"), "w") as log:
    p = subprocess.Popen([sys.executable, "-u", os.path.join(SRC, "feature_head_distill.py"), *ARGS, "--out", OUT],
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env, cwd=SRC)
    for line in p.stdout:
        if "it/s]" in line or "Warning" in line:
            continue
        sys.stdout.write(line)
        log.write(line)
        log.flush()
    rc = p.wait()
print("exit", rc, "minutes", round((time.time() - t0) / 60, 1), flush=True)
'''


# Strict speculation through the client library at 7B on a T4 (benchmarks/sdk_spec_bench.py): the provider service on
# cuda:0, ``pgw.OpenAI`` on the same VM (plain masks: the mask factory is not what is measured), the distilled 7B head
# from the pgw-head-7b kernel's output; off vs draft_head at R = 2 / 3 / 4 on held-out chat and code prompts, every
# answer compared with ``off`` token for token and logprob for logprob. The pgw source goes in a private dataset
# (over Kaggle's script size limit); the head comes in as the head kernel's output (kernel source).
SPEC_KEEP_TESTS = {"sdk", "__init__.py", "conftest.py", "enroll_helpers.py"}
SPEC_KEEP_BENCH = {"sdk_spec_bench.py", "sdk_trip_profile.py", "feature_head_distill.py", "feature_head_train.py",
                   "tree_spec_sim.py"}
SPEC_JOBS: dict[str, dict] = {
    "pgw-spec-7b-t4": {
        "machine_shape": "NvidiaTeslaT4", "source": "dataset", "kernel_sources": ["pgw-head-7b"],
        "steps": [
            {"kind": "shell", "name": "build_native", "required": True, "timeout": 1500,
             "cmd": "{ [ -f $HOME/.cargo/env ] && . $HOME/.cargo/env; true; } && "
                    "(python rust/tools/cargo_ok.py 1.89 || curl -sSf https://sh.rustup.rs | sh -s -- -y --profile "
                    "minimal --default-toolchain stable) && { [ -f $HOME/.cargo/env ] && . $HOME/.cargo/env; true; } "
                    "&& python rust/tools/build_fast.py && python -c 'from pgw.core import native; "
                    "assert native.fast is not None; print(\"pgw_fast\", native.fast.version())'"},
            {"kind": "shell", "name": "sysinfo", "cmd": "nproc; free -g; nvidia-smi; df -h / /tmp; "
             "ls -la /kaggle/input/*/ /kaggle/input/*/*/ || true", "timeout": 120},
            {"kind": "shell", "name": "spec_7b", "timeout": 8400,
             "cmd": "HF_HUB_OFFLINE=0 PGW_BENCH_MASK_GB=15 PYTHONPATH=src:.:benchmarks python benchmarks/sdk_spec_bench.py "
                    "--model qwen2.5-7b-instruct --provider-device cuda "
                    "--head $(find /kaggle/input -name head_d384_v16384.pt | head -1) "
                    "--configs off,head:2,head:3 --chat 2 --code 1 --tokens 48 "
                    "--opt mask_workers=3 --opt mask_wait_s=1800 --opt timeout=7200 --work /tmp "
                    "--json /kaggle/working/spec_7b.json"},
        ]},
}


def build_spec(out_root: Path, owner: str, slug: str, job: dict) -> None:
    """A pgw-source kernel (benchmarks/kaggle/build.py's template and tarball) whose source is a private dataset."""
    import build

    pgw = BENCH.parent
    excl = ["scripts", "examples", "SPEC.md", "INTERFACE_NOTES.md", "STATUS.md", "rust/pgw-core-rs/tests",
            *sorted(f"tests/{p.name}" for p in (pgw / "tests").iterdir() if p.name not in SPEC_KEEP_TESTS),
            *sorted(f"benchmarks/{p.name}" for p in BENCH.iterdir() if p.name not in SPEC_KEEP_BENCH)]
    ds = out_root / f"{slug}-src"
    ds.mkdir(parents=True, exist_ok=True)
    (ds / "pgw.tar.xz").write_bytes(build.source_tarball(tuple(excl)))
    d = out_root / slug
    d.mkdir(parents=True, exist_ok=True)
    template = (HERE / "kernel_template.py").read_text()
    (d / "run.py").write_text(template.replace("__JOB__", json.dumps(job)).replace("__PGW_TGZ_B64__", ""))
    meta = {"id": f"{owner}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "machine_shape": job["machine_shape"], "dataset_sources": [f"{owner}/{slug}-src"],
            "competition_sources": [], "kernel_sources": [f"{owner}/{k}" for k in job.get("kernel_sources", [])],
            "model_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(d, ds, f"{(ds / 'pgw.tar.xz').stat().st_size / 1e6:.2f} MB source")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_root")
    ap.add_argument("--owner", default="bensliv")
    ap.add_argument("--only", nargs="*")
    args = ap.parse_args()
    sys.path.insert(0, str(HERE))
    for slug, job in SPEC_JOBS.items():
        if args.only and slug in args.only:
            build_spec(Path(args.out_root), args.owner, slug, job)
    files = {n: base64.b64encode((BENCH / n).read_bytes()).decode() for n in FILES}
    # short lines (Kaggle rejects very long ones): {"name": ("chunk" "chunk" ...)}
    lit = "{\n" + "".join(f"    {n!r}: (\n" + "".join(f"        {b[i:i + 100]!r}\n" for i in range(0, len(b), 100))
                          + "    ),\n" for n, b in files.items()) + "}"
    for slug, job in JOBS.items():
        if args.only and slug not in args.only:
            continue
        d = Path(args.out_root) / slug
        d.mkdir(parents=True, exist_ok=True)
        (d / "run.py").write_text(TEMPLATE.replace("__FILES__", lit)
                                  .replace("__ARGS__", json.dumps(job["args"])))
        meta = {"id": f"{args.owner}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
                "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
                "machine_shape": job.get("machine_shape", "NvidiaTeslaT4x2"), "dataset_sources": [],
                "competition_sources": [], "kernel_sources": [], "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
        print(d, f"{(d / 'run.py').stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
